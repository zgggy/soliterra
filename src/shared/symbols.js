// Soliterra 符号规范化表（第 93 轮，单点真相）——编辑器自动转换与工具箱「符号规范化」共用。
// 规则：**全角版 ASCII 标点 + 弯引号 → 半角**（这些是把英文符号用全角输入法打出的误用，
//   且在语法位置（[[别名｜]]、![](...)、& 行值）会造成解析失败或悬空链接）。
// 明确保留（不入表，永不转换）：
//   「」『』《》〈〉【】〔〕—— 中文引号/书名号（用户风格，显式要求保留）；
//   （）。，、！？：；—— 中文句读与括号（中文排版标准，误转是破坏而非修复）；
//   ～～（在部分字体与中文语境下作波浪号习惯）除外处理：～(U+FF5E) 入表、〜(U+301C) 保留；
//   全角空格 U+3000 —— 中文缩进常用，保留。
// 改这里 = 编辑器自动转换与工具箱扫描同时变化。
export const SYMBOL_MAP = {
  '｜': '|', '［': '[', '］': ']', '｛': '{', '｝': '}',
  '＜': '<', '＞': '>', '＝': '=', '＋': '+', '－': '-', '＊': '*',
  '／': '/', '＼': '\\', '＠': '@', '＃': '#', '＆': '&', '％': '%',
  '＄': '$', '＾': '^', '＿': '_', '｀': '`', '～': '~', '．': '.',
  '“': '"', '”': '"', '‘': "'", '’': "'",
};

const SYMBOL_RE = new RegExp(`[${Object.keys(SYMBOL_MAP).join('')}]`, 'g');
const SYMBOL_TEST = new RegExp(`[${Object.keys(SYMBOL_MAP).join('')}]`);

/** 是否含可规范化符号（非全局正则——可安全重复调用）。 */
export function containsSymbol(text) { return SYMBOL_TEST.test(String(text)); }

/** 规范化：全角 ASCII 标点 / 弯引号 → 半角；其余字符原样。 */
export function normalizeSymbols(text) {
  return String(text).replace(SYMBOL_RE, (c) => SYMBOL_MAP[c] ?? c);
}
